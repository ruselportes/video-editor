import os
import json
from crewai import Agent, Task, Crew, LLM

# Connect to Local Ollama
# When in Docker, it will use host.docker.internal
ollama_url = os.getenv("OLLAMA_HOST", "http://localhost:11434")

# Set LiteLLM timeout environment variable as a backup
os.environ["LITELLM_TIMEOUT"] = "1800"

local_llm = LLM(
    model="ollama/llama3", 
    base_url=ollama_url,
    timeout=1800 # 30 minutes
)

# Define the Agents
marketer = Agent(
    role='Viral TikTok Copywriter',
    goal='Write a highly engaging, fast-paced script for an affiliate marketing TikTok video.',
    backstory='You are a master of short-form video psychology. You know that the first 3 seconds must have a strong hook, the middle should explain the benefits quickly, and the last 3 seconds must include a call to action pointing to the yellow basket.',
    verbose=True,
    allow_delegation=False,
    llm=local_llm
)

director = Agent(
    role='Video Editor',
    goal='Map available video clips to the script and output the strict Remotion JSON Edit Blueprint.',
    backstory='You are a meticulous video editor. You take a script and a list of available B-roll clips with their descriptions, and you output a perfectly structured JSON file detailing when each clip should play.',
    verbose=True,
    allow_delegation=False,
    llm=local_llm
)

def run_crew_pipeline(product_name: str, clip_descriptions: list) -> str:
    """
    Executes the CrewAI Multi-Agent pipeline.
    Returns the JSON string output.
    """
    clips_context = json.dumps(clip_descriptions, indent=2)
    
    write_script_task = Task(
        description=f'''
        Write a 30-second conversational TikTok script selling a {product_name}.
        You MUST base your visual cues on these available clips:
        {clips_context}

        HONESTY RULES (affiliate content must not mislead buyers):
        - Do NOT invent discount codes, prices, percentages off, giveaways or deadlines.
        - Do NOT claim product features (materials, certifications, RFID, waterproofing, etc.)
          unless they are clearly visible in the clip descriptions or named in the product name.
        - Keep claims general when you are unsure.
        ''',
        expected_output="A 30-second conversational script with visual cues.",
        agent=marketer
    )
    
    build_json_task = Task(
        description=f'''
        Take the script generated by the Copywriter and map it to the available clips provided in the list.
        
        HERE ARE THE ONLY AVAILABLE CLIPS YOU CAN USE:
        {clips_context}
        
        IMPORTANT: For each clip in your edit, you MUST use the EXACT "clip_path" provided in the context 
        (e.g., "clips/your_actual_filename.mp4"). 
        DO NOT invent filenames and DO NOT change the numbers or dates in the filenames. Copy the string exactly.
        
        FRAME CALCULATION (30 FPS):
        - 1 second = 30 frames.
        - A typical clip should be 3-5 seconds long (90 to 150 frames).
        - Ensure the "video_clips" cover the entire duration of the "voiceover_text" (usually 450-900 frames total).
        
        You must output ONLY a valid JSON object matching this exact schema:
        {{
            "project_name": "{product_name}",
            "voiceover_text": "[The full spoken script as a single string]",
            "video_clips": [
                {{
                    "file": "[THE EXACT CLIP_PATH FROM THE LIST]",
                    "start_frame": 0,
                    "end_frame": 90
                }}
            ]
        }}
        ''',
        expected_output="A raw JSON object.",
        agent=director
    )

    video_crew = Crew(
        agents=[marketer, director],
        tasks=[write_script_task, build_json_task],
        verbose=True
    )

    result = video_crew.kickoff()
    
    # FIX: CrewAI returns a CrewOutput object. We need to extract the raw string for the JSON parser.
    return result.raw
